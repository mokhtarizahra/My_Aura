import { Inter, JetBrains_Mono } from 'next/font/google';

import type { Metadata } from 'next';

import { NextIntlClientProvider } from "next-intl";
import { getMessages, setRequestLocale } from "next-intl/server";
import { notFound } from "next/navigation";

import { isLocale, locales } from "@/i18n/request";

import { ThemeProvider } from '@/components/providers/ThemeProvider';
import { AuthProvider } from '@/context/authentication/AuthenticationProvider';

import '../globals.css';

const interSans = Inter({
  variable: '--font-inter-sans',
  subsets: ['latin'],
});

const jetbrainsMono = JetBrains_Mono({
  variable: '--font-jetbrains-mono',
  subsets: ['latin'],
});

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
};

/*
|--------------------------------------------------------------------------
| Static params
|--------------------------------------------------------------------------
|
| Tells Next.js which locales to pre-render at build time.
| Required for static rendering of localized routes.
|
*/
export function generateStaticParams() {
  return locales.map((locale) => ({ locale }));
}

export default async function RootLayout({
  children,
  params: { locale },
}: Readonly<{
  children: React.ReactNode;
  params: { locale: string };
}>) {
  // Reject unknown locales -> render 404
  if (!isLocale(locale)) {
    notFound();
  }

  // Tell next-intl which locale this request is using.
  // Required for server components that call useTranslations/getTranslations.
  setRequestLocale(locale);

  // Load translation messages for the current locale.
  const messages = await getMessages();

  // Persian is RTL, English is LTR.
  const dir = locale === "fa" ? "rtl" : "ltr";

  return (
    <html
      lang={locale}
      dir={dir}
      className={`${interSans.variable} ${jetbrainsMono.variable} h-full antialiased`}
      suppressHydrationWarning
    >
      <body className="min-h-full flex flex-col">
        <NextIntlClientProvider messages={messages}>
          <ThemeProvider>
            <AuthProvider>{children}</AuthProvider>
          </ThemeProvider>
        </NextIntlClientProvider>
      </body>
    </html>
  );
}